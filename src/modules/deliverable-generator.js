/**
 * PickyHack — Formal Pentest Deliverable Generator
 * Produces client-ready penetration testing reports (Print-to-PDF, Markdown, HTML)
 * featuring Executive Summary, CVSS/EPS Risk Matrix, and Technical PoC Dossiers.
 * Guarantees automated credential redaction prior to output.
 */
(function(root) {
  'use strict';

  const DeliverableGenerator = {
    init() {
      if (typeof document === 'undefined') return;
      const btnOpen = document.getElementById('btn-open-deliverable-export');
      const btnFromFindings = document.getElementById('btn-open-report-from-findings');
      const btnPrint = document.getElementById('btn-print-deliverable-pdf');
      const btnMd = document.getElementById('btn-download-deliverable-md');
      const btnHtml = document.getElementById('btn-download-deliverable-html');

      if (btnOpen) btnOpen.addEventListener('click', () => this.openReportWindow());
      if (btnFromFindings) btnFromFindings.addEventListener('click', () => this.openReportWindow());
      if (btnPrint) btnPrint.addEventListener('click', () => window.print());
      if (btnMd) btnMd.addEventListener('click', () => this.downloadMarkdown());
      if (btnHtml) btnHtml.addEventListener('click', () => this.downloadHTML());
    },

    openReportWindow() {
      this.renderReportPreview();
      if (root.WindowManager) root.WindowManager.open('win-report-export');
    },

    generateMarkdown(state) {
      const s = state || (root.ProjectState ? root.ProjectState.get() : root.pentestState) || {};
      const now = new Date().toISOString().split('T')[0];

      if (!s.target && (!s.findings || s.findings.length === 0)) {
        return "# Penetration Testing Formal Deliverable\n\n*No findings recorded yet. Define scope or ingest security scans to compile deliverables.*";
      }

      let md = `# Penetration Testing Formal Deliverable\n\n`;
      md += `**Target:** ${s.target || 'N/A'}\n`;
      md += `**Scope:** ${s.scope || 'N/A'}\n`;
      md += `**Assessment Date:** ${now}\n`;
      md += `**Lead Evaluator:** PickyHack AI Context Harness\n\n`;

      md += `## 1. Executive Summary\n\n`;
      md += `PickyHack completed an offensive security assessment against **${s.target}** within defined scope constraints. `;
      md += `A total of **${(s.findings || []).length}** verified security findings were identified.\n\n`;

      md += `## 2. Risk & Exploitability Matrix\n\n`;
      md += `| Finding | Severity | CVSS | EPS Priority | Target Endpoint |\n`;
      md += `| :--- | :--- | :--- | :--- | :--- |\n`;
      (s.findings || []).forEach(f => {
        md += `| ${f.title} | **${f.severity}** | ${f.cvss || 'N/A'} | ${f.eps || 'N/A'}/100 | \`${f.target}\` |\n`;
      });

      md += `\n## 3. Technical Vulnerability Dossiers\n\n`;
      (s.findings || []).forEach((f, idx) => {
        md += `### 3.${idx + 1}. ${f.title}\n`;
        md += `- **Severity:** ${f.severity} (CVSS ${f.cvss || 'N/A'})\n`;
        md += `- **Exploitability Priority Score (EPS):** ${f.eps || 'N/A'}/100\n`;
        md += `- **Target Endpoint:** \`${f.target}\`\n`;
        if (f.cve && f.cve !== 'N/A') md += `- **CVE Identifier:** ${f.cve}\n`;
        if (f.poc) {
          md += `\n**Proof-of-Concept Evidence / Reproduction Command:**\n\`\`\`bash\n${f.poc}\n\`\`\`\n`;
        }
        md += `\n**Remediation Recommendation:** Apply official vendor security patches immediately and restrict administrative access to internal management networks.\n\n`;
      });

      md += `## 4. Remediation Roadmap\n\n`;
      md += `- [ ] **Immediate (24h):** Remediate all Critical & High findings with active EPS > 80.\n`;
      md += `- [ ] **Short-Term (7d):** Restrict management interfaces behind VPN/MFA barriers.\n`;
      md += `- [ ] **Long-Term (30d):** Implement continuous threat intelligence telemetry & automated regression checks.\n\n`;
      md += `---\n*Confidential Document — Generated by PickyHack Stateless AI Context Harness*\n`;

      // Enforce secret redaction
      const sanitizer = (typeof root !== 'undefined' && root.SecuritySanitizer) || (typeof require !== 'undefined' ? require('../security/sanitizer') : null);
      if (sanitizer) {
        return sanitizer.redact(md).sanitized;
      }
      return md;
    },

    renderReportPreview() {
      const preview = document.getElementById('report-preview-sheet');
      if (!preview) return;

      const s = (root.ProjectState ? root.ProjectState.get() : root.pentestState) || {};
      const findings = s.findings || [];

      if (findings.length === 0) {
        preview.innerHTML = `
          <div class="report-page-preview" style="text-align: center; padding: 48px 16px;">
            <div style="font-size: 32px; margin-bottom: 8px;">📑</div>
            <h3 style="color: #000080; margin-bottom: 6px;">No deliverable content yet.</h3>
            <p style="font-size: 11.5px; color: #666; max-width: 420px; margin: 0 auto; line-height: 1.5;">
              No verified findings have been recorded. Ingest scanner XML/JSON reports via the Burp/ZAP Bridge, or convert notes into findings to generate executive deliverables.
            </p>
          </div>
        `;
        return;
      }

      const criticals = findings.filter(f => f.severity && f.severity.toLowerCase() === 'critical').length;
      const highs = findings.filter(f => f.severity && f.severity.toLowerCase() === 'high').length;
      const mediums = findings.filter(f => f.severity && f.severity.toLowerCase() === 'medium').length;
      const lows = findings.filter(f => f.severity && f.severity.toLowerCase() === 'low').length;

      let html = `
        <div class="report-page-preview">
          <div class="report-header-banner">
            <div>
              <h2 style="font-size: 18px; color: #000080; margin-bottom: 4px;">PickyHack — Formal Security Deliverable</h2>
              <div style="font-size: 11px; color: #666;">Stateless by default. Context-driven by design.</div>
            </div>
            <div style="text-align: right; font-size: 11px; font-family: monospace;">
              <div>Date: ${new Date().toISOString().split('T')[0]}</div>
              <div style="color: #8b0000; font-weight: bold;">CONFIDENTIAL REPORT</div>
            </div>
          </div>

          <hr style="border: 0; border-top: 1px solid #c0c0c0; margin: 12px 0;">

          <h3 style="font-size: 13px; color: #000080; margin-bottom: 6px;">1. Executive Summary &amp; Posture Assessment</h3>
          <p style="font-size: 11.5px; line-height: 1.5; margin-bottom: 10px;">
            During this engagement, PickyHack evaluated the security posture of <strong>${s.target || 'Target Scope'}</strong>.
            A total of <strong>${findings.length}</strong> findings were validated across the attack surface.
          </p>

          <table class="risk-matrix-table" style="width: 100%; border-collapse: collapse; font-size: 11px; margin-bottom: 14px;">
            <thead>
              <tr style="background: #ece9d8; text-align: left;">
                <th style="padding: 4px 6px; border: 1px solid #999;">Critical</th>
                <th style="padding: 4px 6px; border: 1px solid #999;">High</th>
                <th style="padding: 4px 6px; border: 1px solid #999;">Medium</th>
                <th style="padding: 4px 6px; border: 1px solid #999;">Low</th>
                <th style="padding: 4px 6px; border: 1px solid #999;">Total Findings</th>
              </tr>
            </thead>
            <tbody>
              <tr>
                <td style="padding: 6px; border: 1px solid #ccc; color: #8b0000; font-weight: bold;">${criticals}</td>
                <td style="padding: 6px; border: 1px solid #ccc; color: #d9534f; font-weight: bold;">${highs}</td>
                <td style="padding: 6px; border: 1px solid #ccc; color: #f0ad4e; font-weight: bold;">${mediums}</td>
                <td style="padding: 6px; border: 1px solid #ccc; color: #5bc0de;">${lows}</td>
                <td style="padding: 6px; border: 1px solid #ccc; font-weight: bold;">${findings.length}</td>
              </tr>
            </tbody>
          </table>

          <h3 style="font-size: 13px; color: #000080; margin-bottom: 6px;">2. Detailed Technical Findings</h3>
      `;

      findings.forEach((f, idx) => {
        const sevClass = `sev-${(f.severity || 'medium').toLowerCase()}`;
        html += `
          <div style="border: 1px solid #d0d0d0; padding: 8px; margin-bottom: 8px; background: #fafafa;">
            <div style="display: flex; justify-content: space-between; align-items: center; margin-bottom: 4px;">
              <strong style="font-size: 12px;">${idx + 1}. ${f.title}</strong>
              <span class="severity-pill ${sevClass}">${f.severity} (EPS: ${f.eps || 'N/A'}/100)</span>
            </div>
            <div style="font-size: 10.5px; font-family: monospace; color: #555; margin-bottom: 4px;">Target: ${f.target}</div>
            ${f.poc ? `<pre style="background: #ffffff; border: 1px solid #ccc; padding: 4px; font-size: 10px; overflow-x: auto; margin-top: 4px;"><code>${f.poc}</code></pre>` : ''}
          </div>
        `;
      });

      html += `</div>`;

      // Enforce secret redaction on preview HTML
      if (root.SecuritySanitizer) {
        preview.innerHTML = root.SecuritySanitizer.redact(html).sanitized;
      } else {
        preview.innerHTML = html;
      }
    },

    downloadMarkdown() {
      const md = this.generateMarkdown();
      const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `PickyHack_Deliverable_${new Date().toISOString().split('T')[0]}.md`;
      a.click();
      URL.revokeObjectURL(url);
    },

    downloadHTML() {
      const preview = document.getElementById('report-preview-sheet');
      const content = preview ? preview.innerHTML : '<p>Empty report</p>';
      const fullHtml = `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>PickyHack Penetration Testing Deliverable</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; padding: 24px; background: #fff; color: #222; }
    .report-page-preview { max-width: 900px; margin: 0 auto; }
    .severity-pill { display: inline-block; padding: 2px 6px; font-size: 11px; font-weight: bold; border-radius: 3px; }
    .sev-critical { background: #ffcccc; color: #8b0000; }
    .sev-high { background: #ffe0b2; color: #b71c1c; }
    .sev-medium { background: #fff9c4; color: #f57f17; }
    .sev-low { background: #e1f5fe; color: #0277bd; }
  </style>
</head>
<body>
  ${content}
</body>
</html>`;

      const sanitizedHtml = root.SecuritySanitizer ? root.SecuritySanitizer.redact(fullHtml).sanitized : fullHtml;
      const blob = new Blob([sanitizedHtml], { type: 'text/html;charset=utf-8' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `PickyHack_Deliverable_${new Date().toISOString().split('T')[0]}.html`;
      a.click();
      URL.revokeObjectURL(url);
    }
  };

  if (typeof module !== 'undefined' && module.exports) {
    module.exports = DeliverableGenerator;
  }
  root.DeliverableGenerator = DeliverableGenerator;
})(typeof window !== 'undefined' ? window : global);
